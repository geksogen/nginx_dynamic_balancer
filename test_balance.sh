#!/bin/bash

# URL нашего бэкенда
URL="http://localhost/backend"
# Количество запросов для теста
REQUESTS=12

echo "Начинаем тестирование балансировки Nginx..."
echo "Отправляем $REQUESTS запросов на $URL"
echo "------------------------------------------------"

# Цикл от 1 до REQUESTS
for ((i=1; i<=REQUESTS; i++)); do
    # Форматируем вывод номера запроса (например, 01, 02)
    printf "Запрос %02d: " "$i"
    
    # Отправляем запрос (флаг -s скрывает прогресс-бар curl)
    curl -s "$URL"
    
    # Небольшая пауза, чтобы было удобнее наблюдать за выводом
    sleep 0.5
done

echo "------------------------------------------------"
echo "Тестирование завершено."
